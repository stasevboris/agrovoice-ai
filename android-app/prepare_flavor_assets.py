"""Stage only a flavor's manifest-listed assets; verify real assets before APK packaging."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import shutil

import fetch_assets as assets


def asset_files(manifest: dict, voice: dict, tts: dict) -> dict[str, str]:
    files = dict(assets.model_files(manifest))
    files.update({f"voice/ru/{item['path']}": item["sha256"] for item in voice["files"]})
    files.update({f"tts/{tts['model']}/{item['path']}": item["sha256"] for item in tts["files"]})
    return files


def prepare(flavor: str, output: Path, check: bool = False) -> list[str]:
    manifest = assets.flavor_manifest(json.loads(assets.MODEL_MANIFEST.read_text(encoding="utf-8")), flavor)
    voice = json.loads(assets.VOICE_MANIFEST.read_text(encoding="utf-8"))
    tts = json.loads(assets.TTS_MANIFEST.read_text(encoding="utf-8"))
    files = asset_files(manifest, voice, tts)
    metadata = {"models/manifest.json": manifest, "voice/manifest.json": voice, "tts/manifest.json": tts}
    taxonomy = assets.APP.parent / "ml-pipeline/allcrops/taxonomy_v1.json"
    metadata["taxonomies/taxonomy_v1.json"] = json.loads(taxonomy.read_text(encoding="utf-8"))
    if check:
        problems = [path for path, digest in files.items()
                    if not (output / path).is_file() or assets.sha256(output / path) != digest]
        for path, document in metadata.items():
            try:
                if json.loads((output / path).read_text(encoding="utf-8")) != document:
                    problems.append(path)
            except (OSError, ValueError):
                problems.append(path)
        problems += assets.fetch_runtime(True, None)
        return problems

    output.mkdir(parents=True, exist_ok=True)
    expected = set(files) | set(metadata)
    for directory in ("licenses", "knowledge"):
        for source in (assets.ASSETS / directory).rglob("*"):
            if source.is_file():
                relative = source.relative_to(assets.ASSETS).as_posix()
                expected.add(relative)
                target = output / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, target)
    for relative in files:
        source = assets.ASSETS / relative
        target = output / relative
        if source.is_file():
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)
        elif target.is_file():
            target.unlink()
    for relative, document in metadata.items():
        target = output / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    shutil.copyfile(taxonomy, output / "taxonomies/taxonomy_v1.json")
    # This directory is exclusively generated by this task, never a source/bundle directory.
    for target in output.rglob("*"):
        if target.is_file() and target.relative_to(output).as_posix() not in expected:
            target.unlink()
    return []


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--flavor", required=True, choices=("field", "lab"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = assets.APP / "app/build/generated/flavorAssets" / args.flavor
    problems = prepare(args.flavor, output, args.check)
    if problems:
        print("APK packaging requires verified real assets. Run fetch_assets.py --flavor " + args.flavor)
        print("Missing/corrupt: " + ", ".join(problems))
        return 1
    print(f"{args.flavor}: {'verified' if args.check else 'staged'} assets")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
